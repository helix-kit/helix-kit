export const ENTITY_GROUPS: readonly EntityGroup[] = [
  'Taxonomy',
  'Silicon',
  'Products',
  'Claims',
  'Provenance',
];

export const findEntity = (slug: string): EntityDefinition | undefined =>
  ENTITIES.find((entity) => entity.slug === slug);

/** SQL table name → admin slug, so a foreign key can be rendered as a picker. */
const ENTITY_BY_TABLE = new Map(
  ENTITIES.map((entity) => [getTableConfig(entity.table).name, entity.slug]),
);

export const entitySlugForTable = (sqlTableName: string): string | undefined =>
  ENTITY_BY_TABLE.get(sqlTableName);
