/**
 * Every editable entity, in one place: the table it writes, the tRPC router that serves it,
 * and the columns worth showing in a list. The admin pages are generic over this — adding an
 * entity is one entry here, not a new page.
 */

export type EntityGroup = 'Taxonomy' | 'Silicon' | 'Products' | 'Claims' | 'Provenance';

export type EntityDefinition = {
  slug: string;
  label: string;
  group: EntityGroup;
  /** Key of the router in the root router (see `server/trpc.ts`). */
  routerKey: string;
  table: PgTable;
  /** Column shown as this row's name when another entity references it. */
  labelField: string;
  /** Columns rendered in the list, in order. */
  listColumns: readonly string[];
  /** Column that ties this row to its owner, so the list can be filtered to one parent. */
  parentField?: string;
  hint?: string;
};

